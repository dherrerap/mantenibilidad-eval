"""Mutation testing with StrykerJS: how many small faults (mutants) planted in the production code the app's own tests detect.

Coverage says which lines the tests execute; the mutation score says whether the tests would notice if those lines were wrong, which
is a much stronger measure of test quality. Informational (rubric.json `mutation`): the Tests point reports it, no level uses it.

Stryker runs with its command runner, which works with any test framework: for every mutant it runs the package's own `npm test` in
a sandbox copy (the app's files are never modified; node_modules is linked). That executes code generated by a model, like
--run-tests, so it only runs with --mutation AND --run-tests (and after them, so node_modules is installed). It is slow: mutants x
duration of the suite, bounded by `max_minutes_per_package`.

Mutation score = detected / (detected + undetected), with detected = Killed + Timeout and undetected = Survived + NoCoverage
(Stryker's own definition); CompileError, RuntimeError and Ignored mutants are not valid and stay out.
"""
import json
import re
import shutil
from collections import Counter
from pathlib import Path

from evaluator.common import HERE, RUBRIC, rel, sh

STRYKER = HERE / "node_modules" / "@stryker-mutator" / "core" / "bin" / "stryker.js"
DETECTED, UNDETECTED = ("Killed", "Timeout"), ("Survived", "NoCoverage")


def available():
    return STRYKER.exists()


def has_tests(pkg):
    script = (pkg.get("scripts") or {}).get("test", "")
    return bool(script) and "no test specified" not in script


def mutate_files(app, d, ast, nested):
    """Production source files of the package directory `d` (relative to it), without nested packages, configuration, migrations,
    seeders or type declarations: the code whose faults the tests should catch."""
    out = []
    for f in ast["files"]:
        p = (Path(app) / f["path"]).resolve()
        if f["test"] or not str(p).startswith(str(d.resolve())) or any(str(p).startswith(str(n.resolve())) for n in nested):
            continue
        r = rel(p, d)
        if re.search(r"\.config\.|\.d\.ts$|(^|/)(migrations|seeders|seeds)/", r):
            continue
        out.append(r)
    return sorted(out)


def score(counts):
    det = sum(counts.get(s, 0) for s in DETECTED); und = sum(counts.get(s, 0) for s in UNDETECTED)
    return round(100.0 * det / (det + und), 1) if det + und else None


def run_package(d, files, work, test_cmd=None):
    """Stryker on one package. Returns {"dir", "ok", "mutants", "statuses", "score", "survivors": [...], "error"}."""
    T = RUBRIC["mutation"]
    tag = re.sub(r"[^\w.-]", "_", d.name); report = work / f"{tag}.mutation.json"; tmp = work / f"{tag}-sandbox"
    report.unlink(missing_ok=True)
    cfg = {"testRunner": "command", "commandRunner": {"command": test_cmd or "npm test"}, "mutate": files,
           "reporters": ["json"], "jsonReporter": {"fileName": report.as_posix()}, "tempDirName": tmp.as_posix(), "cleanTempDir": True,
           "concurrency": T["concurrency"], "timeoutMS": T["timeout_ms"], "logLevel": "warn", "plugins": [],
           "ignorePatterns": ["coverage", "dist", "build", ".stryker-tmp", "reports"]}
    cfgf = work / f"{tag}.stryker.json"; cfgf.write_text(json.dumps(cfg, indent=1), encoding="utf-8")
    rc, so, se = sh(["node", str(STRYKER), "run", str(cfgf)], cwd=d, timeout=60 * T["max_minutes_per_package"])
    shutil.rmtree(tmp, ignore_errors=True)
    if not report.exists():
        why = "time limit reached" if rc == 124 else ((se or so).strip()[-400:] or f"exit {rc}")
        return {"ok": False, "error": why}
    r = json.loads(report.read_text(encoding="utf-8"))
    counts = Counter(); undetected = []
    for fname, f in (r.get("files") or {}).items():
        for mu in f.get("mutants", []):
            counts[mu["status"]] += 1
            if mu["status"] in UNDETECTED:
                line = ((mu.get("location") or {}).get("start") or {}).get("line")
                undetected.append((fname, line or 0, str(mu.get("mutatorName")), mu["status"], line))
    # the report lists the mutants in the order the workers finished them, which changes between runs: sorted, so the 20 kept are stable
    survivors = [f"{fn}:{line} {mut} ({st})" for fn, _, mut, st, line in sorted(undetected)[:20]]
    return {"ok": True, "mutants": sum(counts.values()), "statuses": dict(counts), "score": score(counts), "survivors": survivors}


def run_mutation(app, pkgs, ast, out, test_cmd=None):
    """Stryker on every package with a test script. {"ok", "tool", "packages": [...], "score", "statuses"}: the score pools the
    mutants of all the packages."""
    if not available():
        return {"ok": False, "error": "StrykerJS is not installed: run `npm install` in the framework folder"}
    app = Path(app).resolve(); work = (Path(out) / "mutation").resolve(); work.mkdir(parents=True, exist_ok=True)
    dirs = [(app / p["dir"]).resolve() for p in pkgs]
    res = {"ok": False, "tool": f"StrykerJS {json.loads((STRYKER.parent.parent / 'package.json').read_text(encoding='utf-8'))['version']} (command runner)",
           "packages": [], "statuses": {}, "score": None}
    total = Counter()
    for p, d in zip(pkgs, dirs):
        if not has_tests(p):
            continue
        nested = [o for o in dirs if o != d and d in o.parents]
        files = mutate_files(app, d, ast, nested)
        if not files:
            res["packages"].append({"dir": p["dir"], "ok": False, "error": "no production source files to mutate"})
            continue
        r = run_package(d, files, work, test_cmd)
        res["packages"].append({"dir": p["dir"], "files": len(files), **r})
        if r["ok"]:
            total.update(r["statuses"]); res["ok"] = True
    res["statuses"] = dict(total); res["score"] = score(total)
    if not res["packages"]:
        res["error"] = "no package with a test script"
    elif not res["ok"]:
        res["error"] = "; ".join(f"{x['dir']}: {x.get('error')}" for x in res["packages"])[:600]
    return res
