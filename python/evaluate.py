def cmd_run(a):
    if model_missing(a.model) and not getattr(a, "allow_missing_model", False):
        raise SystemExit("ERROR: " + MODEL_ERROR)
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    app = Path(a.app).resolve()
    print(f"[1/4] Collecting evidence from {app} …")
    m = collect(app, out, a)
    meta = {"run_id": a.run_id or out.name, "agent": a.agent, "model": a.model, "model_missing": model_missing(a.model), "level": a.level, "domain": a.domain,
            "accept_heuristics": a.accept_heuristics, "run_tests": a.run_tests, "offline": a.offline, "date": m["date"], "as_of": m["as_of"], "mutation": bool(getattr(a, "mutation", False)),
            "manual_file": str(Path(a.manual).resolve()) if a.manual else None}  # so that `rescore` reads the same review
    (out / "meta.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    (out / "metrics.json").write_text(json.dumps(m, indent=1, ensure_ascii=False, default=str), encoding="utf-8")
    (out / "detected_layers.json").write_text(json.dumps(
        {p: {"layer": c, "origin": m["layers_origin"].get(p)} for p, c in m["layers"].items()}, indent=1), encoding="utf-8")
    print("[2/4] Evaluating the 11 points …")
    # the same scoring as `rescore`, on the evidence just collected (manual review, DV8, live database and judge read fresh)
    pts, prof = score(out, json.loads((out / "metrics.json").read_text(encoding="utf-8")), meta, meta["manual_file"])
    print("[3/4] Scorecard, traceability and profile written")
    print(f"[4/4] Maintainability: {fmt_rng(prof['maintainability_min'], prof['maintainability_max'])}/100 · complete={prof['complete']} → {out}")


def cmd_rescore(a):
    """Scores evaluated runs again from their saved evidence: after DV8, the live database, the judge or a manual review."""
    for d in a.res:
        meta, pts, prof = rescore(d)
        print(f"Re-scored {meta.get('run_id', Path(d).name)}: Maintainability: {fmt_rng(prof['maintainability_min'], prof['maintainability_max'])}/100"
              f" · complete={prof['complete']}")


def cmd_aggregate(a):
    root = Path(a.dir); runs = [d for d in sorted(root.iterdir()) if (d / "metrics.json").exists()]
    if not runs:
        raise SystemExit("No runs with metrics.json in " + str(root))
    ms = {d.name: json.loads((d / "metrics.json").read_text(encoding="utf-8")) for d in runs}
    old = [n for n, x in ms.items() if "schema" not in x]
    if old:
        raise SystemExit("These runs were produced by the MERN evaluator (no relational schema in metrics.json): " + ", ".join(old) +
                         ". Re-run 'evaluate' on them, or check out the tag v0.1.0-mern to aggregate them as they were.")
    rows = []
    for d in runs:
        # each run is re-scored with its current inputs (manual review, DV8, live database, judge), not with a frozen copy
        meta = json.loads((d / "meta.json").read_text(encoding="utf-8"))
        pts, prof = score(d, ms[d.name], meta, meta.get("manual_file"))
        acc = None
        if (d / "acceptance.json").exists():
            acc = json.loads((d / "acceptance.json").read_text(encoding="utf-8")).get("acceptance_pct")
        rows.append((meta, pts, prof, (acc, token_columns(d))))
    out = Path(a.out) if a.out else root / "_comparison"; out.mkdir(parents=True, exist_ok=True)
    ids = list(RUBRIC["points"])
    with open(out / "comparison.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f); w.writerow(["run_id", "agent", "level", "domain"] + ids + list(RUBRIC["subcharacteristic_weights"]) + ["maintainability_min", "maintainability_max", "complete", "acceptance_pct"] + list(TOKEN_COLUMNS) + list(ASCMM_COLUMNS))
        for meta, pts, prof, (acc, tok) in rows:
            lv = {p["id"]: (p["level"] or ("not applicable" if p.get("applicable") is False else f"{p['level_min']}…{p['level_max']}")) for p in pts}
            w.writerow([meta["run_id"], meta["agent"], meta["level"], meta["domain"]] + [lv[i] for i in ids] +
                       [fmt_rng(v["min"], v["max"]) for v in prof["subcharacteristics"].values()] + [prof["maintainability_min"], prof["maintainability_max"], prof["complete"], acc] + [tok[k] for k in TOKEN_COLUMNS] + ascmm_columns(prof))
    L = [f"# Comparison ({len(rows)} runs)", "", "| Run | Agent | Level | " + " | ".join(i for i in ids) + " | Overall | Acceptance % | Tokens initial | Tokens R2 | R2 / initial |", "|" + "---|" * (len(ids) + 8)]
    no_model = [meta["run_id"] for meta, _, _, _ in rows if model_missing(meta.get("model"))]
    if no_model:
        L[2:2] = [f"> ⚠ **Generator model not recorded** for {', '.join(no_model)}. {MODEL_WARNING}", ""]
    ab = {"Meets": "✔", "Partial": "◐", "Fails": "✘"}
    for meta, pts, prof, (acc, tok) in rows:
        ratio = tok["tokens_r2_vs_initial"]
        L.append(f"| {meta['run_id']} | {meta['agent']} | {meta['level']} | " + " | ".join("⊘" if p.get("applicable") is False else ab.get(p["level"], "?") for p in pts) + f" | {fmt_rng(prof['maintainability_min'], prof['maintainability_max'])} | {'n/a' if acc is None else acc} | "
                 f"{tu.fmt(tok['tokens_initial_total'])} | {tu.fmt(tok['tokens_r2_total'])} | {'n/a' if ratio is None else f'×{ratio:.2f}'} |")
    L += [""] + ascmm_comparison_md([(meta["run_id"], prof) for meta, _, prof, _ in rows])
    sens = sensitivity([(meta, pts) for meta, pts, _, _ in rows])
    (out / "sensitivity.json").write_text(json.dumps(sens, indent=1, ensure_ascii=False), encoding="utf-8")
    L += [""] + sensitivity_md(sens)
    (out / "comparison.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"Comparison written to {out} ({len(rows)} runs)")


