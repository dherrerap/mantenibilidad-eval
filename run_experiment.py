#!/usr/bin/env python3
"""
run_experiment.py — Full pipeline of an experiment:
  generate (agent) → acceptance gate (PostgreSQL from the app's docker-compose.yml) → [R2: additional requirements (agent)]
  → evaluate maintainability → comparison.

Phases (--phase, comma-separated, always run in this order):
  initial  creates the project from technical-<level>.md + requirements-<domain>.md with combiner-prompt.md (saved as PROMPT.md)
  r2       applies specs/r2-additional-requirements.md on top of the existing project with r2-prompt.md (saved as PROMPT-R2.md)

The agent only sees the prompt and the .md files of its phase; the evaluation and the token measurement are NEVER mentioned to
it, so as not to contaminate its design decisions.

Tokens: the agent's CLI runs with its machine-readable output (claude --output-format json, codex exec --json) and the tokens
of each phase are recorded with token_usage.py in token-usage/<run_id>.json and copied to results/<run_id>/token_usage.json.
With --agent-cmd the output is parsed too; if it carries no usage, record the phase by hand (python token_usage.py record).

Examples
  # one cell
  python3 run_experiment.py --agent claude --level N2
  # full matrix (2 agents × 3 levels × 1 repetition)
  python3 run_experiment.py --agent claude,codex --level N1,N2,N3
  # creation and then the additional requirements, measuring the tokens of each phase
  python3 run_experiment.py --agent claude --level N1 --domain cinema --phase initial,r2
  # only the additional requirements, on a project this script created earlier
  python3 run_experiment.py --agent claude --level N1 --domain cinema --phase r2
  # evaluate an app that already exists (without invoking the agent)
  python3 run_experiment.py --agent claude --level N1 --existing-app ./my_app --skip-acceptance

Outputs in experiments/<id>/{project/, agent.log, agent-r2.log, acceptance.json, contract_conformance.json, meta.json} and
results/<id>/ (scorecard, traceability, profile, token_usage.json, and the copies of acceptance.json and contract_conformance.json).
At the end: results/_comparison/.

The acceptance gate (acceptance_check.py) starts the PostgreSQL service of the evaluated app's own docker-compose.yml (project
name eval_<run>), creates a disposable database eval_<run> in it, runs the backend with DATABASE_URL and PORT set, waits until
PostgreSQL and the backend are ready, runs the checks of the minimum HTTP interface of the domain (--domain) through a Prism proxy
that also checks every response against the app's OpenAPI contract (contract_conformance.json, informational) and tears everything
down (containers and volumes). If Docker or Docker Compose is not available the gate is SKIPPED with a clear message (it is not a
silent failure) and the maintainability evaluation continues. The suites cover the ORIGINAL requirements, so the gate runs right
after phase initial (before r2); on a project that already implements r2 it is skipped and the earlier result is kept.

Windows: the agent's executable is resolved through PATH (claude.cmd, codex.cmd) and the prompt goes on standard input.

SECURITY: runs code generated by an LLM (npm install/start/test). Run this in a
disposable container or VM.
"""
import argparse, datetime, itertools, json, os, shlex, shutil, subprocess, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pg_runtime as rt  # noqa: E402
import evaluate as ev  # noqa: E402
import token_usage as tu  # noqa: E402

SPECS = HERE / "specs"
# Default commands. VERIFY the flags with `claude --help` / `codex exec --help` for YOUR version.
# The prompt goes on STANDARD INPUT (`claude -p` reads it when no prompt argument is given; `codex exec -` reads it): a multi-line
# argument does not survive the npm .cmd wrappers on Windows. A custom --agent-cmd may still put {prompt} in the arguments.
# The machine-readable output (JSON / JSONL) carries the token usage that token_usage.py records for each phase.
AGENTS = {
    "claude": ["claude", "-p", "--output-format", "json", "--dangerously-skip-permissions"],
    "codex": ["codex", "exec", "--json", "--full-auto", "-"],
}
PROMPT_ARG = "{prompt}"
PHASES = ("initial", "r2")
R2_SPEC = "r2-additional-requirements.md"
ACCEPTANCE_FILE = "acceptance.json"
CONFORMANCE_FILE = "contract_conformance.json"  # written by acceptance_check.py --app next to acceptance.json


def resolve(cmd):
    """The command with its executable resolved through PATH/PATHEXT: on Windows `claude` is often `claude.cmd`, which
    subprocess does not find without a shell."""
    return [shutil.which(cmd[0]) or cmd[0]] + list(cmd[1:])


def sh(cmd, cwd=None, timeout=None, env=None, log=None, stdin_text=None):
    try:
        p = subprocess.run(resolve(cmd), cwd=cwd, env=env, timeout=timeout, text=True, encoding="utf-8", errors="replace",
                           input=stdin_text, stdin=None if stdin_text is not None else subprocess.DEVNULL,
                           stdout=log or subprocess.PIPE, stderr=subprocess.STDOUT)
        return p.returncode
    except subprocess.TimeoutExpired:
        return 124
    except FileNotFoundError:
        return 127


def agent_command(agent, a, prompt):
    """(argv, stdin text): the prompt goes in the arguments only when the template has {prompt}, otherwise on standard input."""
    tpl = shlex.split(a.agent_cmd) if a.agent_cmd else AGENTS[agent]
    if any(PROMPT_ARG in x for x in tpl):
        cmd, stdin_text = [x.replace(PROMPT_ARG, prompt) for x in tpl], None
    else:
        cmd, stdin_text = list(tpl), prompt
    if a.model and not a.agent_cmd:
        cmd += ["--model", a.model]
    return cmd, stdin_text


def build_prompt(level, domain="ecommerce"):
    return (SPECS / "combiner-prompt.md").read_text(encoding="utf-8").replace("{LEVEL}", level.lower()).replace("{DOMAIN}", domain)


def build_r2_prompt():
    return (SPECS / "r2-prompt.md").read_text(encoding="utf-8")


def prepare_phase(phase, level, domain, project):
    """Copies the inputs of the phase into the project and returns the prompt (also saved there, as in the manual procedure)."""
    if phase == "initial":
        project.mkdir(parents=True, exist_ok=True)
        for f in (f"technical-{level.lower()}.md", f"requirements-{domain}.md"):
            shutil.copy(SPECS / f, project / f)
        prompt = build_prompt(level, domain)
        (project / "PROMPT.md").write_text(prompt, encoding="utf-8")
    else:
        if not (project / "backend").is_dir():
            raise SystemExit(f"Phase r2 needs the project of phase initial and {project / 'backend'} does not exist "
                             "(run --phase initial first, or pass --existing-app).")
        shutil.copy(SPECS / R2_SPEC, project / R2_SPEC)
        prompt = build_r2_prompt()
        (project / "PROMPT-R2.md").write_text(prompt, encoding="utf-8")
    return prompt


def generate(agent, level, a, expdir, project, phase="initial"):
    prompt = prepare_phase(phase, level, a.domain, project)
    cmd, stdin_text = agent_command(agent, a, prompt)
    exe = shutil.which(cmd[0])
    ver = subprocess.run([exe, "--version"], capture_output=True, text=True).stdout.strip() if exe else "n/a"
    log_file = expdir / ("agent.log" if phase == "initial" else f"agent-{phase}.log")
    t0 = time.time()
    with open(log_file, "w", encoding="utf-8") as log:
        rc = sh(cmd, cwd=project, timeout=a.agent_timeout, log=log, stdin_text=stdin_text)
    if rc == 127:
        print(f"  ERROR: '{cmd[0]}' was not found on PATH. Install the agent's CLI or pass --agent-cmd with the full path.")
    return {"agent_cmd": cmd[0], "agent_version": ver, "rc": rc, "seconds": round(time.time() - t0), "log": log_file.name}


def record_tokens(run_id, phase, log_file, usage_dir):
    """Records the tokens of the phase from the agent's output; returns the phase totals, or None when the output has no usage."""
    try:
        session = tu.parse_file(log_file)
    except (ValueError, OSError):
        return None
    data = tu.record_phase(tu.usage_path(run_id, usage_dir), run_id, phase, [session], note=f"run_experiment.py ({Path(log_file).name})")
    return data["phases"][phase]["totals"]


def run_backend_gate(be, env, port, expdir, wait=90, domain="ecommerce"):
    """npm install + npm start with the given environment, acceptance_check.py (suite of `domain`) against it, backend stopped at the end."""
    with open(expdir / "backend.log", "w", encoding="utf-8") as log:
        if sh([rt.npm(), "install", "--no-audit", "--no-fund"], cwd=be, timeout=900, log=log) != 0:
            return {"error": "npm install failed (see backend.log)"}
        proc = rt.start_process([rt.npm(), "start"], be, env, log)
        try:
            if not rt.wait_for_port(port, wait):
                return {"error": f"the backend did not open the port within {wait} s (see backend.log)"}
            time.sleep(2)  # margin for the schema creation and the initial data
            # --app: also through Prism against the app's OpenAPI contract (contract_conformance.json, informational)
            sh([sys.executable, str(HERE / "acceptance_check.py"), "--base", f"http://127.0.0.1:{port}", "--domain", domain,
                "--out", str(expdir / ACCEPTANCE_FILE), "--app", str(be.parent)], log=log)
        finally:
            rt.kill_tree(proc)
    f = expdir / ACCEPTANCE_FILE
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {"error": "acceptance_check.py produced no result (see backend.log)"}


def acceptance(project, expdir, run_id, wait=90, domain="ecommerce"):
    """Functional gate against PostgreSQL started from the app's own docker-compose.yml, with the suite of `domain`.

    Returns the acceptance.json content, {"skipped": True, "reason": …} when Docker is not available, or {"error": …}.
    Containers and volumes (and with them the disposable database eval_<run>) are always removed at the end."""
    be = Path(project) / "backend"
    if not be.exists():
        return {"error": "backend/ does not exist"}
    compose_file = rt.find_compose(project)
    if compose_file is None:
        return {"error": "docker-compose.yml not found at the project root (it is a delivery condition of the specification)"}
    cmd, why = rt.docker_status()
    if cmd is None:
        return {"skipped": True, "reason": why}
    (expdir / ACCEPTANCE_FILE).unlink(missing_ok=True)
    (expdir / CONFORMANCE_FILE).unlink(missing_ok=True)
    name = rt.eval_db_name(run_id)  # compose project name and disposable database name
    compose = rt.Compose(cmd, compose_file, name, expdir / "compose.log")
    (expdir / "compose.log").write_text("", encoding="utf-8")
    try:
        cfg = compose.config()
        svc = rt.pick_postgres_service(cfg)
        if not svc:
            return {"error": "no PostgreSQL service found in docker-compose.yml (image postgres or POSTGRES_* variables)"}
        user, password, _ = rt.pg_credentials(cfg["services"][svc])
        rc, _, err = compose.up(svc)
        if rc != 0:
            return {"error": "docker compose up failed (see compose.log): " + rt.mask(err, "")[-200:]}
        port = compose.port(svc)
        if not port:
            return {"error": f"service {svc} does not publish port 5432 to the host, so the gate cannot connect to it"}
        if not compose.wait_ready(svc, user) or not rt.wait_for_port(port, 30):
            return {"error": "PostgreSQL did not become ready in time (see compose.log)"}
        if compose.create_database(svc, user, name)[0] != 0:
            return {"error": f"could not create the disposable database {name} (see compose.log)"}
        backend_port = rt.free_port()
        env = {k: v for k, v in os.environ.items() if k != "PG_ADMIN_URL"}
        env.update({"PORT": str(backend_port), "DATABASE_URL": rt.build_url(user, password, "127.0.0.1", port, name)})
        env.update(rt.backend_secrets(be, env))  # random JWT_SECRET & co., or a backend that validates them does not start
        result = run_backend_gate(be, env, backend_port, expdir, wait, domain)
        log = expdir / "backend.log"
        if log.exists():
            log.write_text(rt.mask(log.read_text(encoding="utf-8", errors="replace"), env["DATABASE_URL"]), encoding="utf-8")
        return result
    except (RuntimeError, ValueError) as e:
        return {"error": str(e)}
    finally:
        compose.down()


def run_phases(phases, agent, level, a, expdir, project, meta, usage_key, after_phase=None):
    """Runs the agent for each phase and records its tokens; keeps in meta what earlier invocations recorded (other phases and
    the acceptance gate). `after_phase(phase)` is called once each phase has finished."""
    if (expdir / "meta.json").exists():  # e.g. initial and its gate, when only r2 runs now
        old = json.loads((expdir / "meta.json").read_text(encoding="utf-8"))
        meta.update({k: v for k, v in old.items() if k.startswith("generation") or k == "acceptance"})
    for phase in phases:
        key = "generation" if phase == "initial" else f"generation_{phase}"
        print(f"[{phase}] invoking the agent …")
        g = meta[key] = generate(agent, level, a, expdir, project, phase)
        g["tokens"] = tok = record_tokens(usage_key, phase, expdir / g["log"], a.usage_dir)
        print(f"  rc={g['rc']} in {g['seconds']} s (log: {expdir / g['log']})")
        if tok:
            print(f"  tokens: {tu.fmt(tok['total_tokens'])} (input {tu.fmt(tok['input_tokens'])}, output {tu.fmt(tok['output_tokens'])})")
        else:
            print(f"  WARNING: the agent's output carries no token usage; record it by hand: python token_usage.py record {usage_key} --phase {phase} …")
        if after_phase:
            after_phase(phase)


def run_gate(project, expdir, run_id, domain, state):
    """Acceptance gate with the suite of the domain; `state` (e.g. "after phase initial") is recorded in acceptance.json."""
    print(f"[acceptance] {state}: starting PostgreSQL (docker compose), the backend and running the {domain} cases …")
    acc = acceptance(project, expdir, run_id, domain=domain)
    if acc.get("skipped"):
        print(f"   SKIPPED: {acc['reason']}. The functional gate was not run for {run_id}.")
    elif acc.get("error"):
        print("   ERROR:", acc["error"])
    else:
        print(f"   {acc['passed']}/{acc['total']} cases")
        acc["state"] = state
        (expdir / ACCEPTANCE_FILE).write_text(json.dumps(acc, indent=1, ensure_ascii=False), encoding="utf-8")
    return acc


def gate_after_phases(phases, project, expdir, run_id, a, meta):
    """The gate when it did not run right after phase initial in this invocation: on the project as it is, unless it already
    implements r2 (the suites cover the original requirements), in which case an earlier result is kept or the gate is skipped."""
    if "initial" in phases:
        return
    if not rt.has_r2(project):
        meta["acceptance"] = run_gate(project, expdir, run_id, a.domain, "project as found")
    elif meta.get("acceptance") and not meta["acceptance"].get("skipped"):
        print("[acceptance] the project implements r2: keeping the result of the gate run after phase initial.")
    else:
        meta["acceptance"] = {"skipped": True, "reason": rt.R2_GATE_SKIP}
        print(f"[acceptance] SKIPPED: {rt.R2_GATE_SKIP}.")


def evaluate_run(project, res, run_id, agent, level, a):
    """Maintainability evaluation of the project (plus DV8 when requested) into `res`."""
    print("[evaluation] measuring maintainability …")
    cmd = [sys.executable, str(HERE / "evaluate.py"), "run", str(project), "--out", str(res),
           "--agent", agent, "--model", a.model or "n/a", "--level", level, "--domain", a.domain, "--run-id", run_id]
    if ev.model_missing(a.model): cmd.append("--allow-missing-model")
    if not a.skip_tests: cmd.append("--run-tests")
    if not a.skip_tests and getattr(a, "mutation", False): cmd.append("--mutation")
    if a.accept_heuristics: cmd.append("--accept-heuristics")
    if a.offline: cmd.append("--offline")
    if getattr(a, "as_of", None): cmd += ["--as-of", a.as_of]
    sh(cmd, log=sys.stdout)
    if a.dv8:  # DL/PC with DV8, then a re-score (no new collection) to bring them into the profile
        print("[dv8] computing DL and PC …")
        if sh([sys.executable, str(HERE / "dv8_metrics.py"), str(res)], log=sys.stdout) == 0:
            sh([sys.executable, str(HERE / "evaluate.py"), "rescore", str(res)], log=sys.stdout)


def main():
    for s_ in (sys.stdout, sys.stderr):  # Windows console (cp1252): avoids UnicodeEncodeError with →, ·, ≥
        s_.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--agent", default="claude", help="claude, codex (comma-separated)")
    ap.add_argument("--level", default="N1,N2,N3")
    ap.add_argument("--domain", default="ecommerce", help="ecommerce, cinema (specs/requirements-<domain>.md)")
    ap.add_argument("--phase", help="initial, r2 or initial,r2; none = only evaluate (default: initial, or none with --existing-app)")
    ap.add_argument("--usage-dir", default=tu.DEFAULT_DIR, help="where the token records are written (default token-usage)")
    ap.add_argument("--repetitions", type=int, default=1)
    ap.add_argument("--model", help="REQUIRED: the generator model (also passed to the agent's CLI as --model unless --agent-cmd is used)")
    ap.add_argument("--allow-missing-model", action="store_true", help="run without --model (profile.md and report.md carry a warning)")
    ap.add_argument("--agent-cmd", help='custom template with {prompt}, e.g. "my-agent --run {prompt}"')
    ap.add_argument("--agent-timeout", type=int, default=3600)
    ap.add_argument("--skip-acceptance", action="store_true", help="do not run the functional gate (it needs Docker)")
    ap.add_argument("--skip-tests", action="store_true", help="do not run the project's tests during the evaluation")
    ap.add_argument("--existing-app", help="evaluate this directory instead of invoking the agent")
    ap.add_argument("--dv8", action="store_true", help="compute DL and PC with DV8 (see dv8_metrics.py)")
    ap.add_argument("--accept-heuristics", action="store_true")
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--mutation", action="store_true", help="mutation testing with StrykerJS on the app's tests (slow; informational)")
    ap.add_argument("--as-of", dest="as_of", help="reference date YYYY-MM-DD of versions and advisories (default: the evaluation date)")
    ap.add_argument("--exp", default="experiments"); ap.add_argument("--results", default="results")
    a = ap.parse_args()
    a.phase = a.phase or ("none" if a.existing_app else "initial")
    phases = [] if a.phase == "none" else [p.strip().lower() for p in a.phase.split(",")]
    if any(p not in PHASES for p in phases):
        sys.exit(f"ERROR: --phase accepts {', '.join(PHASES)} (comma-separated) or none")
    phases = [p for p in PHASES if p in phases]
    if a.existing_app and "initial" in phases:
        sys.exit("ERROR: an --existing-app is already created: use --phase r2 or --phase none")
    if not (SPECS / f"requirements-{a.domain}.md").exists():
        sys.exit(f"ERROR: specs/requirements-{a.domain}.md does not exist")

    if ev.model_missing(a.model) and not a.allow_missing_model:
        sys.exit("ERROR: " + ev.MODEL_ERROR)
    exp_root, res_root = Path(a.exp).resolve(), Path(a.results).resolve()
    ev.record_generator_model(res_root, a.model)
    if not a.skip_acceptance:
        cmd, why = rt.docker_status()
        if cmd is None:
            print(f"WARNING: {why}. The acceptance gate will be SKIPPED for every run: the results will not say whether the apps work.")
    for agent, level, rep in itertools.product(a.agent.split(","), a.level.split(","), range(1, a.repetitions + 1)):
        run_id = f"{agent}-{level.lower()}-{a.domain}-r{rep}"
        expdir = exp_root / run_id; expdir.mkdir(parents=True, exist_ok=True)
        project = Path(a.existing_app).resolve() if a.existing_app else expdir / "project"
        usage_key = project.name if a.existing_app else run_id  # same key as `token_usage.py record <app>` and cli.py
        print(f"\n=== {run_id} ===")
        meta = {"run_id": run_id, "agent": agent, "level": level, "domain": a.domain, "repetition": rep,
                "model": a.model, "date": datetime.datetime.now().isoformat(timespec="seconds")}
        def after_phase(phase, project=project, expdir=expdir, run_id=run_id, meta=meta):
            # the suites cover the original requirements: the gate runs on the state right after phase initial, before r2
            if phase == "initial" and not a.skip_acceptance:
                meta["acceptance"] = run_gate(project, expdir, run_id, a.domain, "after phase initial")
        run_phases(phases, agent, level, a, expdir, project, meta, usage_key, after_phase)
        if not a.skip_acceptance:
            gate_after_phases(phases, project, expdir, run_id, a, meta)
        (expdir / "meta.json").write_text(json.dumps(meta, indent=1, ensure_ascii=False), encoding="utf-8")
        evaluate_run(project, res_root / run_id, run_id, agent, level, a)
        for f in (ACCEPTANCE_FILE, CONFORMANCE_FILE):
            if (expdir / f).exists():
                shutil.copy(expdir / f, res_root / run_id / f)
        if tu.usage_path(usage_key, a.usage_dir).exists():
            shutil.copy(tu.usage_path(usage_key, a.usage_dir), res_root / run_id / tu.RESULT_FILE)
    print("\n=== comparison ===")
    sh([sys.executable, str(HERE / "evaluate.py"), "aggregate", str(res_root)], log=sys.stdout)


if __name__ == "__main__":
    main()
