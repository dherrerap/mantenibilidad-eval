#!/usr/bin/env python3
"""
run_experiment.py — Full pipeline of an experiment:
  generate (agent) → acceptance gate (PostgreSQL from the app's docker-compose.yml) → evaluate maintainability → comparison.

The agent only sees the prompt and the two .md files (technical-<level>.md and requirements); the
evaluation is NEVER mentioned to it, so as not to contaminate its design decisions.

Examples
  # one cell
  python3 run_experiment.py --agent claude --level N2
  # full matrix (2 agents × 3 levels × 1 repetition)
  python3 run_experiment.py --agent claude,codex --level N1,N2,N3
  # evaluate an app that already exists (without invoking the agent)
  python3 run_experiment.py --agent claude --level N1 --existing-app ./my_app --skip-acceptance

Outputs in experiments/<id>/{project/, agent.log, acceptance.json, meta.json} and
results/<id>/ (scorecard, traceability, profile). At the end: results/_comparison/.

The acceptance gate (acceptance_check.py) starts the PostgreSQL service of the evaluated app's own docker-compose.yml (project
name eval_<run>), creates a disposable database eval_<run> in it, runs the backend with DATABASE_URL and PORT set, waits until
PostgreSQL and the backend are ready, runs the checks of the minimum HTTP interface and tears everything down (containers and
volumes). If Docker or Docker Compose is not available the gate is SKIPPED with a clear message (it is not a silent failure) and
the maintainability evaluation continues.

SECURITY: runs code generated by an LLM (npm install/start/test). Run this in a
disposable container or VM.
"""
import argparse, datetime, itertools, json, os, shlex, shutil, subprocess, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pg_runtime as rt  # noqa: E402
import evaluate as ev  # noqa: E402

SPECS = HERE / "specs"
# Default commands. VERIFY the flags with `claude --help` / `codex exec --help` for YOUR version.
AGENTS = {
    "claude": ["claude", "-p", "{prompt}", "--dangerously-skip-permissions"],
    "codex": ["codex", "exec", "--full-auto", "{prompt}"],
}


def sh(cmd, cwd=None, timeout=None, env=None, log=None):
    try:
        p = subprocess.run(cmd, cwd=cwd, env=env, timeout=timeout, text=True,
                           stdout=log or subprocess.PIPE, stderr=subprocess.STDOUT)
        return p.returncode
    except subprocess.TimeoutExpired:
        return 124
    except FileNotFoundError:
        return 127


def build_prompt(level):
    return (SPECS / "combiner-prompt.md").read_text(encoding="utf-8").replace("{LEVEL}", level.lower())


def generate(agent, level, a, expdir, project):
    project.mkdir(parents=True, exist_ok=True)
    for f in (f"technical-{level.lower()}.md", "requirements-ecommerce.md"):
        shutil.copy(SPECS / f, project / f)
    tpl = shlex.split(a.agent_cmd) if a.agent_cmd else AGENTS[agent]
    cmd = [x.replace("{prompt}", build_prompt(level)) for x in tpl]
    if a.model and not a.agent_cmd:
        cmd += ["--model", a.model]
    ver = subprocess.run([tpl[0], "--version"], capture_output=True, text=True).stdout.strip() if shutil.which(tpl[0]) else "n/a"
    t0 = time.time()
    with open(expdir / "agent.log", "w", encoding="utf-8") as log:
        rc = sh(cmd, cwd=project, timeout=a.agent_timeout, log=log)
    return {"agent_cmd": tpl[0], "agent_version": ver, "rc": rc, "seconds": round(time.time() - t0)}


def run_backend_gate(be, env, port, expdir, wait=90):
    """npm install + npm start with the given environment, acceptance_check.py against it, backend stopped at the end."""
    with open(expdir / "backend.log", "w", encoding="utf-8") as log:
        if sh([rt.npm(), "install", "--no-audit", "--no-fund"], cwd=be, timeout=900, log=log) != 0:
            return {"error": "npm install failed (see backend.log)"}
        proc = rt.start_process([rt.npm(), "start"], be, env, log)
        try:
            if not rt.wait_for_port(port, wait):
                return {"error": f"the backend did not open the port within {wait} s (see backend.log)"}
            time.sleep(2)  # margin for the schema creation and the initial data
            sh([sys.executable, str(HERE / "acceptance_check.py"), "--base", f"http://127.0.0.1:{port}", "--out", str(expdir / "acceptance.json")], log=log)
        finally:
            rt.kill_tree(proc)
    f = expdir / "acceptance.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {"error": "acceptance_check.py produced no result (see backend.log)"}


def acceptance(project, expdir, run_id, wait=90):
    """Functional gate against PostgreSQL started from the app's own docker-compose.yml.

    Returns the acceptance.json content, {"skipped": True, "reason": …} when Docker is not available, or {"error": …}.
    Containers and volumes (and with them the disposable database eval_<run>) are always removed at the end."""
    be = Path(project) / "backend"
    if not be.exists():
        return {"error": "backend/ does not exist"}
    compose_file = rt.find_compose(project)
    if compose_file is None:
        return {"error": "docker-compose.yml not found at the project root (it is a delivery condition of the specification)"}
    cmd, why = rt.docker_status()
    if cmd is None:
        return {"skipped": True, "reason": why}
    (expdir / "acceptance.json").unlink(missing_ok=True)
    name = rt.eval_db_name(run_id)  # compose project name and disposable database name
    compose = rt.Compose(cmd, compose_file, name, expdir / "compose.log")
    (expdir / "compose.log").write_text("", encoding="utf-8")
    try:
        cfg = compose.config()
        svc = rt.pick_postgres_service(cfg)
        if not svc:
            return {"error": "no PostgreSQL service found in docker-compose.yml (image postgres or POSTGRES_* variables)"}
        user, password, _ = rt.pg_credentials(cfg["services"][svc])
        rc, _, err = compose.up(svc)
        if rc != 0:
            return {"error": "docker compose up failed (see compose.log): " + rt.mask(err, "")[-200:]}
        port = compose.port(svc)
        if not port:
            return {"error": f"service {svc} does not publish port 5432 to the host, so the gate cannot connect to it"}
        if not compose.wait_ready(svc, user) or not rt.wait_for_port(port, 30):
            return {"error": "PostgreSQL did not become ready in time (see compose.log)"}
        if compose.create_database(svc, user, name)[0] != 0:
            return {"error": f"could not create the disposable database {name} (see compose.log)"}
        backend_port = rt.free_port()
        env = {k: v for k, v in os.environ.items() if k != "PG_ADMIN_URL"}
        env.update({"PORT": str(backend_port), "DATABASE_URL": rt.build_url(user, password, "127.0.0.1", port, name)})
        result = run_backend_gate(be, env, backend_port, expdir, wait)
        log = expdir / "backend.log"
        if log.exists():
            log.write_text(rt.mask(log.read_text(encoding="utf-8", errors="replace"), env["DATABASE_URL"]), encoding="utf-8")
        return result
    except (RuntimeError, ValueError) as e:
        return {"error": str(e)}
    finally:
        compose.down()


def main():
    for s_ in (sys.stdout, sys.stderr):  # Windows console (cp1252): avoids UnicodeEncodeError with →, ·, ≥
        s_.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--agent", default="claude", help="claude, codex (comma-separated)")
    ap.add_argument("--level", default="N1,N2,N3")
    ap.add_argument("--domain", default="ecommerce")
    ap.add_argument("--repetitions", type=int, default=1)
    ap.add_argument("--model", help="REQUIRED: the generator model (also passed to the agent's CLI as --model unless --agent-cmd is used)")
    ap.add_argument("--allow-missing-model", action="store_true", help="run without --model (profile.md and report.md carry a warning)")
    ap.add_argument("--agent-cmd", help='custom template with {prompt}, e.g. "my-agent --run {prompt}"')
    ap.add_argument("--agent-timeout", type=int, default=3600)
    ap.add_argument("--skip-acceptance", action="store_true", help="do not run the functional gate (it needs Docker)")
    ap.add_argument("--skip-tests", action="store_true", help="do not run the project's tests during the evaluation")
    ap.add_argument("--existing-app", help="evaluate this directory instead of invoking the agent")
    ap.add_argument("--dv8", action="store_true", help="compute DL and PC with DV8 (see dv8_metrics.py)")
    ap.add_argument("--accept-heuristics", action="store_true")
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--exp", default="experiments"); ap.add_argument("--results", default="results")
    a = ap.parse_args()

    if ev.model_missing(a.model) and not a.allow_missing_model:
        sys.exit("ERROR: " + ev.MODEL_ERROR)
    exp_root, res_root = Path(a.exp).resolve(), Path(a.results).resolve()
    ev.record_generator_model(res_root, a.model)
    if not a.skip_acceptance:
        cmd, why = rt.docker_status()
        if cmd is None:
            print(f"WARNING: {why}. The acceptance gate will be SKIPPED for every run: the results will not say whether the apps work.")
    for agent, level, rep in itertools.product(a.agent.split(","), a.level.split(","), range(1, a.repetitions + 1)):
        run_id = f"{agent}-{level.lower()}-{a.domain}-r{rep}"
        expdir = exp_root / run_id; expdir.mkdir(parents=True, exist_ok=True)
        project = Path(a.existing_app).resolve() if a.existing_app else expdir / "project"
        print(f"\n=== {run_id} ===")
        meta = {"run_id": run_id, "agent": agent, "level": level, "domain": a.domain, "repetition": rep,
                "model": a.model, "date": datetime.datetime.now().isoformat(timespec="seconds")}
        if not a.existing_app:
            print("[generation] invoking the agent …")
            meta["generation"] = generate(agent, level, a, expdir, project)
            print(f"  rc={meta['generation']['rc']} in {meta['generation']['seconds']} s (log: {expdir / 'agent.log'})")
        if not a.skip_acceptance:
            print("[acceptance] starting PostgreSQL (docker compose), the backend and running cases …")
            meta["acceptance"] = acceptance(project, expdir, run_id)
            acc = meta["acceptance"]
            if acc.get("skipped"):
                print(f"   SKIPPED: {acc['reason']}. The functional gate was not run for {run_id}.")
            elif acc.get("error"):
                print("   ERROR:", acc["error"])
            else:
                print(f"   {acc['passed']}/{acc['total']} cases")
        (expdir / "meta.json").write_text(json.dumps(meta, indent=1, ensure_ascii=False))
        print("[evaluation] measuring maintainability …")
        cmd = [sys.executable, str(HERE / "evaluate.py"), "run", str(project), "--out", str(res_root / run_id),
               "--agent", agent, "--model", a.model or "n/a", "--level", level, "--domain", a.domain, "--run-id", run_id]
        if ev.model_missing(a.model): cmd.append("--allow-missing-model")
        if not a.skip_tests: cmd.append("--run-tests")
        if a.accept_heuristics: cmd.append("--accept-heuristics")
        if a.offline: cmd.append("--offline")
        sh(cmd, log=sys.stdout)
        if a.dv8:  # DL/PC with DV8 and a second pass to bring them into the profile
            print("[dv8] computing DL and PC …")
            if sh([sys.executable, str(HERE / "dv8_metrics.py"), str(res_root / run_id)], log=sys.stdout) == 0:
                sh(cmd, log=sys.stdout)
        if (expdir / "acceptance.json").exists():
            shutil.copy(expdir / "acceptance.json", res_root / run_id / "acceptance.json")
    print("\n=== comparison ===")
    sh([sys.executable, str(HERE / "evaluate.py"), "aggregate", str(res_root)], log=sys.stdout)


if __name__ == "__main__":
    main()
