#!/usr/bin/env python3
"""
mongo_analysis.py — Data model analysis on a real MongoDB database (what one would do by hand with MongoDB Compass).

For an already evaluated run: starts the app's backend against a new database (eval_<run>), exercises it with the acceptance
gate (acceptance_check.py, which also says whether the app works), dumps the observed schema, indexes and validators with
mongo_schema.js and drops the database. Writes to <res>/:
    mongo_schema.json   observed schema, indexes and validators per collection (used by evaluate.py and judge.py)
    acceptance.json     result of the functional gate
    seed.json           users and orders created by seed_api.py (same script for all apps)
    backend.log         backend output (with the database password masked)

The password is NOT saved in any file: it is read from the MONGO_URI environment variable (without a database name):
    set MONGO_URI=mongodb+srv://user:password@cluster0.xxxx.mongodb.net/        (PowerShell: $env:MONGO_URI = "...")
    python mongo_analysis.py results/claude-n1-ecommerce-r1

SECURITY: runs code generated by a model (npm install and the backend) and gives it access to that database. Use a test
cluster and a user with permissions only on eval_* databases; rotate the password if you shared it.
"""
import argparse, json, os, re, shutil, socket, subprocess, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent


def uri_for(base, db):
    """Inserts the database name into a MongoDB URI that lacks one."""
    head, _, query = base.partition("?")
    head = head.rstrip("/")
    return f"{head}/{db}?{query or 'retryWrites=true&w=majority'}"


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0)); return s.getsockname()[1]


def wait_for_port(port, seconds):
    end = time.time() + seconds
    while time.time() < end:
        try:
            socket.create_connection(("127.0.0.1", port), timeout=1).close(); return True
        except OSError:
            time.sleep(1)
    return False


def kill(proc):
    if os.name == "nt":
        subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"], capture_output=True)
    else:
        proc.terminate()


def mask(text, base):
    m = re.match(r"mongodb(?:\+srv)?://[^:]+:([^@]+)@", base)
    return text.replace(m.group(1), "***") if m and m.group(1) else text


def main():
    for s_ in (sys.stdout, sys.stderr):
        s_.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("res", help="results folder of a run (with metrics.json)")
    ap.add_argument("--app", help="app folder (by default, the one in metrics.json)")
    ap.add_argument("--skip-seed", action="store_true", dest="skip_seed", help="do not create the common data from seed_api.py")
    ap.add_argument("--keep", action="store_true", help="do not drop the database when finished")
    ap.add_argument("--wait", type=int, default=90, help="seconds for the backend to open the port")
    a = ap.parse_args()
    base = os.environ.get("MONGO_URI")
    if not base:
        sys.exit("Set the MONGO_URI environment variable (MongoDB URI without a database name). See the help: -h")
    res = Path(a.res).resolve()
    meta = json.loads((res / "meta.json").read_text(encoding="utf-8"))
    app = Path(a.app or json.loads((res / "metrics.json").read_text(encoding="utf-8"))["app"]).resolve()
    be = app / "backend"
    if not be.exists():
        sys.exit(f"{be} does not exist")
    db = "eval_" + re.sub(r"\W", "_", meta.get("run_id", res.name))[:30]
    uri = uri_for(base, db)
    port = free_port()
    env = {**os.environ, "PORT": str(port), "MONGODB_URI": uri, "MONGO_URI": uri}
    npm = shutil.which("npm") or "npm"
    log = res / "backend.log"
    state = {}
    print(f"Database {db}; backend on port {port} …")
    with open(log, "w", encoding="utf-8") as lf:
        if not (be / "node_modules").exists():
            subprocess.run([npm, "install", "--no-audit", "--no-fund"], cwd=be, stdout=lf, stderr=subprocess.STDOUT, timeout=900)
        proc = subprocess.Popen([npm, "start"], cwd=be, env=env, stdout=lf, stderr=subprocess.STDOUT)
        try:
            if not wait_for_port(port, a.wait):
                state["error"] = f"the backend did not open the port within {a.wait} s (see backend.log)"
            else:
                time.sleep(2)  # margin for the initial seed and index creation
                subprocess.run([sys.executable, str(HERE / "acceptance_check.py"), "--base", f"http://127.0.0.1:{port}",
                                "--out", str(res / "acceptance.json")], stdout=lf, stderr=subprocess.STDOUT, timeout=600)
                if not a.skip_seed:  # same users and orders in every app: the observed schema is comparable
                    subprocess.run([sys.executable, str(HERE / "seed_api.py"), "--base", f"http://127.0.0.1:{port}",
                                    "--output", str(res / "seed.json")], stdout=lf, stderr=subprocess.STDOUT, timeout=600)
                time.sleep(1)
        finally:
            kill(proc)
    if "error" not in state:
        cmd = ["node", str(HERE / "mongo_schema.js"), str(res / "mongo_schema.json")] + ([] if a.keep else ["--drop"])
        p = subprocess.run(cmd, env={**os.environ, "MONGO_URI": uri}, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=300)
        print(mask((p.stdout + p.stderr).strip(), base))
        if p.returncode != 0:
            state["error"] = "mongo_schema.js failed"
    log.write_text(mask(log.read_text(encoding="utf-8", errors="replace"), base), encoding="utf-8")
    if (res / "acceptance.json").exists():
        acc = json.loads((res / "acceptance.json").read_text(encoding="utf-8"))
        print(f"Acceptance: {acc.get('acceptance_pct', 'n/a')} %")
    if "error" in state:
        print("ERROR:", state["error"]); return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
