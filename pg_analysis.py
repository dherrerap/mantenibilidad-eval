#!/usr/bin/env python3
"""
pg_analysis.py — Data model analysis on a real PostgreSQL database.

For an already evaluated run: creates a fresh database eval_<run>, starts the app's backend against it, exercises it with the
acceptance gate (acceptance_check.py, which also says whether the app works) and with pg_seed.py (the same 25 users and their orders in
every app), reads the catalog of the real database with pg_schema.js (information_schema and pg_catalog: columns, constraints, foreign
keys, indexes, index usage) and drops the database. Writes to <res>/:
    pg_schema.json     catalog of the real database (used by evaluate.py and judge.py for C1, C3, C4 and C6)
    acceptance.json    result of the functional gate
    seed.json          users and orders created by pg_seed.py
    backend.log        backend output (passwords masked)

The password is NOT saved in any file: it is read from the PG_ADMIN_URL environment variable, a connection string of a role that can
create databases (CREATEDB, not a superuser). The scripts only ever create, read and drop databases named eval_<...>:
    export PG_ADMIN_URL=postgres://evaluator:secret@localhost:5432/postgres        (PowerShell: $env:PG_ADMIN_URL = "...")
    python pg_analysis.py results/claude-n1-ecommerce-r1

The backend is started with DATABASE_URL pointing at that database (same role) and PORT; PG_ADMIN_URL itself is NOT passed to it.

SECURITY: runs code generated by a model (npm install and the backend) with access to that role. Use a disposable server (for example
a throwaway container) and a role without superuser rights; rotate the password if you shared it.
"""
import argparse, json, os, subprocess, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pg_runtime as rt  # noqa: E402


def node_pg(args, admin_url, timeout=300):
    """Runs pg_schema.js; returns (returncode, masked output)."""
    p = subprocess.run(["node", str(HERE / "pg_schema.js")] + list(args), env={**os.environ, "PG_ADMIN_URL": admin_url},
                       capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=timeout)
    return p.returncode, rt.mask((p.stdout + p.stderr).strip(), admin_url)


def exercise_backend(be, env, port, res, wait, skip_seed, log):
    """npm install + npm start, acceptance gate and seed. Returns an error text or None."""
    if not (be / "node_modules").exists():
        subprocess.run([rt.npm(), "install", "--no-audit", "--no-fund"], cwd=be, stdout=log, stderr=subprocess.STDOUT, timeout=900)
    proc = rt.start_process([rt.npm(), "start"], be, env, log)
    try:
        if not rt.wait_for_port(port, wait):
            return f"the backend did not open the port within {wait} s (see backend.log)"
        time.sleep(2)  # margin for the schema creation and the initial data
        base = f"http://127.0.0.1:{port}"
        subprocess.run([sys.executable, str(HERE / "acceptance_check.py"), "--base", base, "--out", str(res / "acceptance.json")],
                       stdout=log, stderr=subprocess.STDOUT, timeout=600)
        if not skip_seed:  # same users and orders in every app: the data left in the database is comparable
            subprocess.run([sys.executable, str(HERE / "pg_seed.py"), "--base", base, "--output", str(res / "seed.json")],
                           stdout=log, stderr=subprocess.STDOUT, timeout=600)
        time.sleep(2)  # let PostgreSQL report index usage before the catalog is read
        return None
    finally:
        rt.kill_tree(proc)


def analyze(res, admin_url, app=None, skip_seed=False, keep=False, wait=90):
    """Returns (error or None, database name). The database is dropped at the end unless `keep`."""
    res = Path(res).resolve()
    meta = json.loads((res / "meta.json").read_text(encoding="utf-8"))
    app = Path(app or json.loads((res / "metrics.json").read_text(encoding="utf-8"))["app"]).resolve()
    be = app / "backend"
    if not be.exists():
        return f"{be} does not exist", None
    db = rt.eval_db_name(meta.get("run_id", res.name))
    if not rt.valid_eval_db(db):
        return f"refusing database name {db!r}", db
    url, port = rt.db_url(admin_url, db), rt.free_port()
    env = {k: v for k, v in os.environ.items() if k != "PG_ADMIN_URL"}
    env.update({"PORT": str(port), "DATABASE_URL": url})
    print(f"Database {db}; backend on port {port} …")
    rc, out = node_pg(["create", db], admin_url)
    print(out)
    if rc != 0:
        return "could not create the database (see above)", db
    error = None
    try:
        with open(res / "backend.log", "w", encoding="utf-8") as log:
            error = exercise_backend(be, env, port, res, wait, skip_seed, log)
        if error is None:
            rc, out = node_pg(["dump", db, str(res / "pg_schema.json")], admin_url)
            print(out)
            if rc != 0:
                error = "pg_schema.js dump failed"
            elif not json.loads((res / "pg_schema.json").read_text(encoding="utf-8")).get("tables"):
                (res / "pg_schema.json").unlink()  # nothing to read: evaluate.py falls back to the static analysis
                error = "the database has no tables after exercising the app (does `npm start` create the schema?); static analysis is used"
    finally:
        if not keep:
            rc, out = node_pg(["drop", db], admin_url)
            print(out)
            if rc != 0:
                error = (error + "; " if error else "") + f"COULD NOT DROP {db}: drop it by hand"
        log_file = res / "backend.log"
        if log_file.exists():
            log_file.write_text(rt.mask(log_file.read_text(encoding="utf-8", errors="replace"), admin_url), encoding="utf-8")
    if (res / "acceptance.json").exists():
        print(f"Acceptance: {json.loads((res / 'acceptance.json').read_text(encoding='utf-8')).get('acceptance_pct', 'n/a')} %")
    return error, db


def main():
    for s_ in (sys.stdout, sys.stderr):
        s_.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("res", help="results folder of a run (with metrics.json)")
    ap.add_argument("--app", help="app folder (by default, the one in metrics.json)")
    ap.add_argument("--skip-seed", action="store_true", dest="skip_seed", help="do not create the common data from pg_seed.py")
    ap.add_argument("--keep", action="store_true", help="do not drop the database when finished")
    ap.add_argument("--wait", type=int, default=90, help="seconds for the backend to open the port")
    a = ap.parse_args()
    admin = os.environ.get("PG_ADMIN_URL")
    if not admin:
        sys.exit("Set the PG_ADMIN_URL environment variable (connection string of a role that can create databases). See the help: -h")
    error, _ = analyze(a.res, admin, a.app, a.skip_seed, a.keep, a.wait)
    if error:
        print("ERROR:", error)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
