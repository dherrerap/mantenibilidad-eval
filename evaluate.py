def parse_lcov(lcov, d):
    """Sums LF/LH/BRF/BRH from an lcov.info. Node only reports the files the tests load, so unloaded .js/.ts
    sources are added with 0 covered lines (equivalent to Jest's collectCoverageFrom); their branches cannot be
    counted without instrumenting them and stay out of the denominator."""
    tot = {"lines_total": 0, "lines_cov": 0, "br_total": 0, "br_cov": 0, "unloaded": 0}
    seen = set()
    for ln in lcov.read_text(encoding="utf-8", errors="replace").splitlines():
        if ln.startswith("SF:"): seen.add(os.path.normcase(os.path.normpath(str((d / ln[3:]) if not os.path.isabs(ln[3:]) else ln[3:]))))
        elif ln.startswith("LF:"): tot["lines_total"] += int(ln[3:])
        elif ln.startswith("LH:"): tot["lines_cov"] += int(ln[3:])
        elif ln.startswith("BRF:"): tot["br_total"] += int(ln[4:])
        elif ln.startswith("BRH:"): tot["br_cov"] += int(ln[4:])
    for f in walk(d):
        f = Path(f)
        if f.suffix not in (".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs"): continue
        if re.search(r"\.(test|spec)\.", f.name) or {"tests", "__tests__", "coverage"} & set(f.parts): continue
        if os.path.normcase(os.path.normpath(str(f))) in seen: continue
        try: n = sum(1 for x in f.read_text(encoding="utf-8", errors="replace").splitlines() if x.strip())
        except OSError: continue
        tot["lines_total"] += n; tot["unloaded"] += 1
    return tot


def run_tests(app, pkgs, test_cmd, out):
    res = {"executed": True, "packages": [], "lines_total": 0, "lines_cov": 0, "br_total": 0, "br_cov": 0, "all_passed": True, "ran_any": False}
    for p in pkgs:
        script = p["scripts"].get("test", "")
        if not script or "no test specified" in script:
            continue
        d = Path(app) / p["dir"]
        if not (d / "node_modules").exists():
            sh(["npm", "install", "--no-audit", "--no-fund"], cwd=d, timeout=900)
        native = (not test_cmd) and bool(re.search(r"\bnode\b.*--test\b|node:test", script))
        lcov = d / "coverage" / "lcov.info"
        c8 = BIN / ("c8.cmd" if os.name == "nt" else "c8")
        runner = "node:test"
        if native and c8.exists():
            # c8 --all also instruments the sources that no test loads: lines and branches with the full denominator
            runner = "c8"
            cmd = [str(c8), "--all", "--src=.", "--reporter=lcovonly", "--reports-dir=coverage",
                   "--exclude=**/{tests,test,__tests__,coverage,dist,build}/**", "--exclude=**/*.{test,spec}.*",
                   "--exclude=**/*.config.*", shutil.which("node") or "node", "--test"]
        elif native:
            # without c8: Node's native runner (node --test); branches of unloaded files stay out of the denominator
            lcov.parent.mkdir(exist_ok=True)
            cmd = [shutil.which("node") or "node", "--test", "--experimental-test-coverage",
                   "--test-coverage-exclude=**/*.test.*", "--test-coverage-exclude=**/{tests,__tests__,coverage}/**",
                   "--test-reporter=spec", "--test-reporter-destination=stdout",
                   "--test-reporter=lcov", f"--test-reporter-destination={lcov}"]
        else:
            cmd = test_cmd.split() if test_cmd else ["npm", "test", "--silent", "--", "--coverage",
                                                     "--coverageReporters=json-summary", "--watchAll=false",
                                                     # without this Jest only measures the files the tests import (inflated coverage)
                                                     "--collectCoverageFrom=**/*.{js,jsx,ts,tsx}", "--collectCoverageFrom=!**/node_modules/**",
                                                     "--collectCoverageFrom=!**/{tests,__tests__,coverage,dist,build}/**", "--collectCoverageFrom=!**/*.{test,spec}.*"]
        env = {**os.environ, "CI": "true"}
        rc, so, se = sh(cmd, cwd=d, timeout=900, env=env)
        entry = {"dir": p["dir"], "rc": rc, "tail": (so + se)[-400:]}
        res["ran_any"] = True
        if rc != 0:
            res["all_passed"] = False
        cs = d / "coverage" / "coverage-summary.json"
        if native and lcov.exists():
            t = parse_lcov(lcov, d)
            res["lines_total"] += t["lines_total"]; res["lines_cov"] += t["lines_cov"]
            res["br_total"] += t["br_total"]; res["br_cov"] += t["br_cov"]
            entry["coverage"] = {"lines": round(100.0 * t["lines_cov"] / t["lines_total"], 1) if t["lines_total"] else 0.0,
                                 "branches": round(100.0 * t["br_cov"] / t["br_total"], 1) if t["br_total"] else 0.0,
                                 "runner": runner, "unloaded_files": t["unloaded"]}
        elif cs.exists():
            t = json.loads(cs.read_text())["total"]
            res["lines_total"] += t["lines"]["total"]; res["lines_cov"] += t["lines"]["covered"]
            res["br_total"] += t["branches"]["total"]; res["br_cov"] += t["branches"]["covered"]
            entry["coverage"] = {"lines": t["lines"]["pct"], "branches": t["branches"]["pct"]}
        res["packages"].append(entry)
    return res


def run_duplication(app, out):
    """Code clones (copy-paste) with jscpd. Returns {ok, pct, clones, duplicated_lines, lines, top}."""
    T = RUBRIC["thresholds"]["duplication"]
    jscpd = HERE / "node_modules" / "jscpd" / "bin" / "jscpd"  # via node: Windows' .cmd splits the arguments at commas
    if not jscpd.exists():
        return {"ok": False, "reason": "jscpd not installed (npm install)"}
    d = out / "jscpd"; shutil.rmtree(d, ignore_errors=True)
    ign = ",".join([f"**/{x}/**" for x in ("node_modules", "tests", "test", "__tests__", "coverage", "dist", "build")] +
                   ["**/*.test.*", "**/*.spec.*", "**/*.min.js"])
    rc, so, se = sh(["node", str(jscpd), Path(app).as_posix(), "--silent", "--reporters", "json", "--output", d.as_posix(),
                     "--min-lines", str(T["min_lines"]), "--min-tokens", str(T["min_tokens"]),
                     "--format", "javascript,typescript,jsx,tsx", "--ignore", ign], timeout=300)
    rep = d / "jscpd-report.json"
    if not rep.exists():
        return {"ok": False, "reason": (se or so)[-200:] or f"rc={rc}"}
    r = json.loads(rep.read_text(encoding="utf-8")); t = r["statistics"]["total"]
    top = sorted(r.get("duplicates", []), key=lambda c: -c["lines"])[:5]
    name = lambda f: os.path.relpath(Path(f).resolve(), Path(app).resolve()).replace("\\", "/")  # jscpd reports them relative to the cwd
    return {"ok": True, "pct": t["percentage"], "clones": t["clones"], "duplicated_lines": t["duplicatedLines"], "lines": t["lines"],
            "top": [f"{name(c['firstFile']['name'])}:{c['firstFile']['start']} ≈ {name(c['secondFile']['name'])}:{c['secondFile']['start']} ({c['lines']} lines)" for c in top]}


def classify_layers(ast, app, override):
    L = RUBRIC["default_layers"]
    names = ["presentation", "business", "data", "shared"]
    ov = None
    if override and Path(override).exists():
        ov = {k: [glob_to_re(g) for g in v] for k, v in json.loads(Path(override).read_text()).items() if not k.startswith("_")}
    out = {}; origin = {}
    for f in ast["files"]:
        if f["test"] or f["frontend"]:
            continue
        p = f["path"]
        layer = None
        if ov:
            for k, rs in ov.items():
                if any(r.match(p) for r in rs):
                    layer = k; origin[p] = "override"; break
        else:
            parts = p.lower().split("/")
            stem = re.sub(r"([a-z])([A-Z])", r"\1.\2", Path(p).stem).lower()
            tokens = [t for t in re.split(r"[.\-_]", stem) if t] + list(reversed(parts[:-1]))
            norm = lambda s: s.rstrip("s")
            # Architectural layers first (token closest to the file); 'shared' only if nothing else matches
            for group in (names[:3], names[3:]):
                for tok in tokens:
                    for n in group:
                        if norm(tok) in {norm(k) for k in L[n]}:
                            layer = n; origin[p] = tok; break
                    if layer:
                        break
                if layer:
                    break
        if layer:
            out[p] = layer
    return out, origin


def read_sql_files(app, max_bytes=2_000_000):
    """[(relative path, text)] of the application's *.sql files (migrations, schema dumps), in a stable order."""
    out = []
    for p in walk(app):
        if p.suffix.lower() == ".sql" and p.stat().st_size <= max_bytes:
            out.append((rel(p, app), p.read_text(encoding="utf-8", errors="replace")))
    return sorted(out)


def readme_text(app):
    for p in walk(app):
        if p.name.lower() == "readme.md" and "node_modules" not in p.parts:
            return p.read_text(encoding="utf-8", errors="ignore")
    return ""


def inventory_artifacts(m, files):
    """Step 2 / Table 27: which input artifacts exist, classified as core, complementary or optional.
    `files` = relative paths of the application. Each entry of rubric.json "artifacts" gets `present` and a `detail`."""
    low = [f.lower() for f in files]
    found = lambda rx: [f for f, l in zip(files, low) if re.search(rx, l)]
    deps = {d for p in m["packages"]["packages"] for d in {**p["dependencies"], **p["devDependencies"]}}
    obs_libs = sorted(deps & set(RUBRIC["libs_logger"] + RUBRIC["libs_request_logger"] + RUBRIC["libs_metrics"]))
    prod = [f for f in m["ast"]["files"] if not f["test"]]
    ts, tr = m["tests_static"], m["tests_run"]
