#!/usr/bin/env python3
"""
evaluate.py — Automation of the maintainability evaluation framework (PIA-02).

Applies the protocol of section 5.3.3 to a PERN application generated by an agent:
collects the generated artifacts and classifies them into core, complementary and optional
(step 2, Table 27), gathers evidence (steps 3-4), evaluates the 11 decision points with the rubric of
Table 26 (steps 5-7), builds the traceability matrix (step 8), applies the weighting scheme to the
classified findings (step 9) and builds the maintainability risk dashboard following the rules of
Table 29, flagging the decision points that cannot be evaluated for lack of evidence (step 10).
Whatever cannot be automated is explicitly left "pending" and reported as a RANGE [minimum, maximum]
until the evaluator completes it in manual.json.

USAGE
  python3 evaluate.py run <app_dir> --out results/claude-n2-ecommerce \
        --agent claude --model "claude-sonnet-5-5" --level N2 --domain ecommerce \
        [--run-tests] [--test-cmd "npm test -- --coverage ..."] [--offline]
        [--accept-heuristics] [--manual manual.json] [--layers layers.json] [--allow-missing-model]
  python3 evaluate.py aggregate results/ [--out results/_comparison]

The generator model (--model) is a variable of the experiment and is REQUIRED: without it `run` stops with an error. With
--allow-missing-model it evaluates anyway and profile.md / report.md carry a prominent warning.

SECURITY: --run-tests installs dependencies and runs code generated by an LLM
(untrusted). Use it inside a disposable container/VM.
"""
