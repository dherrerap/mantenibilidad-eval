def eval_cohesion(m, manual, opts):
    T = RUBRIC["thresholds"]["cohesion"]
    fns = [f for f in m["ast"]["functions"] if not f["test"]]
    hi = [f for f in fns if f["fanout"] > T["fanout_max"]]
    p = pct(len(hi), len(fns))
